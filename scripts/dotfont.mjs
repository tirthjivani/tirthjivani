export const SUPPORTED = new Set(Object.keys(G));

/** Upcases, folds accents and common emoji, and drops anything unsupported. */
export function normalize(input) {
  return input
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/<3|❤️?|💖|💙|💚|💛|💜|🖤|🤍|🧡/gu, "♥")
    .replace(/->/g, "→")
    .replace(/[‘’`]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, "-")
    .toUpperCase()
    .split("")
    .filter((ch) => SUPPORTED.has(ch))
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Lays text out as lit dots. Returns { cols, dots: [[col, row], …] } with one
 * blank column between glyphs.
 */
export function layout(text) {
  const dots = [];
  let col = 0;
  [...text].forEach((ch, i) => {
    const glyph = G[ch];
    if (!glyph) return;
    if (i > 0) col += 1;
    glyph.forEach((row, r) => {
      [...row].forEach((cell, c) => cell === "#" && dots.push([col + c, r]));
    });
    col += glyph[0].length;
  });
  return { cols: col, dots };
}
